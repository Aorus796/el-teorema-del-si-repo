/*
 * Pixel-art indexado de las estanterias de biblioteca de `library`
 * (Biblioteca del Margen -- Library Visual Polish, v1.1). Migra las 6
 * decoraciones que antes usaban el tipo compartido "tables" (un simple
 * bloque marron + "mantel" claro, ver la rama "tables" de WorldScene.js
 * que sigue sirviendo a `archive`) a un tipo exclusivo que se lee como
 * una estanteria real: marco de madera, baldas horizontales y filas de
 * lomos de libros con varios tonos.
 *
 * Dos variantes de tamano, mismo patron que PIER_SIDE/PIER_CENTER en
 * pierPixelArt.js: "wide" (144x32, para las estanterias
 * noroeste/noreste) y "narrow" (112x32, para las otras cuatro). Ambas
 * comparten la misma paleta y la misma estructura de filas (marco
 * superior, 3 compartimentos de libros separados por baldas, marco
 * inferior); solo cambia el ancho interior. Generadas
 * proceduralmente (ver scratch-generate-library-art.mjs, script de un
 * solo uso, no forma parte del repositorio) a partir de una regla de
 * diseno fija -- anchos/alturas/colores de libro en ciclo determinista,
 * con hueco oscuro ("b") sobre los libros mas bajos para dar sensacion
 * de profundidad/volumen -- para garantizar exactamente 32 filas y el
 * ancho declarado sin errores de transcripcion manual.
 */

